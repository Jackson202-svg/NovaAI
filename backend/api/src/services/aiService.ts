import { logger } from '../lib/logger';
import { env } from '../config/env';

export interface ChatCompletionPayload {
  message: string;
  conversationId?: string;
  model?: string;
  context?: Array<{ role: 'user' | 'assistant' | 'system'; content: string }>;
}

export const generateChatResponse = async ({ message, conversationId, model, context }: ChatCompletionPayload): Promise<string> => {
  const activeModel = model ?? env.openAiModel;

  if (!env.openAiApiKey) {
    logger.info({ conversationId, activeModel }, 'Using local fallback chat response');
    return `NovaAI (${activeModel}): ${message}\n\nThis response is generated by the local fallback engine. Configure OPENAI_API_KEY to use the cloud provider.`;
  }

  try {
    const response = await fetch(`${env.openAiBaseUrl}/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${env.openAiApiKey}`,
      },
      body: JSON.stringify({
        model: activeModel,
        messages: [
          ...(context ?? []).map((entry) => ({ role: entry.role, content: entry.content })),
          { role: 'user', content: message },
        ],
      }),
    });

    if (!response.ok) {
      throw new Error(`Provider call failed with status ${response.status}`);
    }

    const payload = (await response.json()) as {
      choices?: Array<{ message?: { content?: string } }>;
    };

    return payload.choices?.[0]?.message?.content ?? 'NovaAI: No content returned by the model.';
  } catch (error) {
    logger.warn({ error }, 'OpenAI fallback triggered');
    return `NovaAI (${activeModel}): ${message}\n\nThe model provider call failed, so this fallback message was generated locally to keep the service responsive.`;
  }
};
